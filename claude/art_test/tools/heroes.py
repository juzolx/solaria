"""Solaria style test: assemble 2x heroes from AI img2img sprites that share one pose.

Every race body and outfit was generated by img2img from the same small mannequin
(C:/ai/art_work/base_tall.png or base_short.png), so they land on the same 128x128 native grid
in the same place. We cut a fixed window, clean each piece, then build layers:
  body   = the race sprite (head, skin, plain clothes)
  outfit = an outfit sprite below the neck line, minus skin-coloured pixels (hands show the race)
  weapon = a separate sprite pinned to the hand
"""
import sys
import numpy as np
from PIL import Image
sys.path.insert(0, r"C:\ai\scripts")
import pixlib as P

RAW = "C:/ai/art_raw/"
WIN = (40, 46, 86, 90)  # native-grid window (46x44) holding every figure, with room for the outline

PICKS = {
    "race": {
        "human": "r2_human_d60_s52", "elf": "r2_elf_d72_s53", "orc": "r2_orc_d60_s53",
        "dwarf": "r2_dwarf_d60_s52", "goblin": "r2_goblin_d60_s51",
    },
    "outfit": {
        ("warrior", "tall"): "o2_warrior_tall_d55_s52", ("warrior", "short"): "o2_warrior_short_d68_s52",
        ("mage", "tall"): "o2_mage_tall_d55_s51", ("mage", "short"): "o2_mage_short_d68_s52",
        ("ranger", "tall"): "o2_ranger_tall_d55_s51", ("ranger", "short"): "o2_ranger_short_d68_s52",
    },
}
BUILD = {"human": "tall", "elf": "tall", "orc": "tall", "dwarf": "short", "goblin": "short"}
# neck line (window rows): head above, outfit below
NECK = {"tall": 22, "short": 26}

_cache = {}


def native(name):
    if name not in _cache:
        raw, nobg, grid, nat = P.native_of(RAW + name + ".png")
        win = nat.crop(WIN)
        a = P.keep_largest(P.to_np(win), 0.05)
        _cache[name] = (raw, P.to_im(a))
    return _cache[name]


def strip_shadow_fixed(im):
    """Shadow peel without cropping (keeps the window aligned)."""
    bb = im.getbbox()
    f = P.strip_shadow(im.crop(bb))
    out = Image.new("RGBA", im.size, (0, 0, 0, 0))
    out.alpha_composite(f, (bb[0], bb[1]))
    return out


def clean(im, max_colors=18):
    q = P.quantize(strip_shadow_fixed(im), max_colors)
    return q


def skin_mask(a, skin_lab, tol=0.06):
    lab = P.oklab(a[..., :3].astype(float))
    m = np.zeros(a.shape[:2], bool)
    for s in skin_lab:
        m |= ((lab - s) ** 2).sum(-1) < tol ** 2
    return m & (a[..., 3] > 0)


def outfit_layer(outfit_im, build):
    a = P.to_np(outfit_im).copy()
    a[:NECK[build], :, 3] = 0
    # skin of the human mannequin (sampled from the outfit sprite's own face rows)
    face = a.copy()
    face_src = P.to_np(outfit_im)[NECK[build] - 10:NECK[build]]
    op = face_src[..., 3] > 0
    lab = P.oklab(face_src[..., :3][op].astype(float))
    ch = np.hypot(lab[:, 1], lab[:, 2])
    skin = lab[(lab[:, 0] > 0.6) & (ch > 0.03) & (lab[:, 1] > 0.0)]
    if len(skin):
        uniq = np.unique(np.round(skin, 3), axis=0)
        a[skin_mask(a, uniq), 3] = 0
    return P.to_im(a)


def compose(race, outfit=None, weapon=None, rim=True):
    build = BUILD[race]
    body = clean(native(PICKS["race"][race])[1])
    img = body.copy()
    if outfit:
        o = clean(native(PICKS["outfit"][(outfit, build)])[1])
        # below the neck the outfit decides the silhouette: clip the body to it
        ba, oa = P.to_np(img).copy(), P.to_np(o)
        clip = (oa[..., 3] == 0)
        clip[:NECK[build]] = False
        ba[clip, 3] = 0
        img = P.to_im(ba)
        img.alpha_composite(outfit_layer(o, build))
    out = P.outline(img)
    if rim:
        out = P.rim(out)
    return out  # (48x46) art px: window + outline ring


WEAPONS = {
    # name: (raw file, figure index on that sheet, flip vertical, target length, grip (x, y) after scaling)
    "sword": ("weapon_sword_s12", 9, True, 26),
    "staff": ("weapon_staff_s12", 0, False, 36),
}


def weapon(name):
    f, i, vflip, length = WEAPONS[name]
    raw, figs = P.figures(RAW + f + ".png", hmin=10, hmax=120)
    nat = figs[i]["img"]
    w = nat.transpose(Image.FLIP_TOP_BOTTOM) if vflip else nat
    if w.height > length:
        w = P.shrink_mode(w, height=length, max_colors=14)
    w = P.quantize(w, 10)
    return nat, P.outline(w)


def grip_of(wim, name):
    """Grip point: sword just under the crossguard (widest row in the lower half), staff at 55%."""
    a = P.to_np(wim)
    h = a.shape[0]
    if name == "sword":
        widths = [(a[y, :, 3] > 0).sum() for y in range(h)]
        guard = max(range(h // 2, h), key=lambda y: widths[y])
        cols = np.where(a[guard + 2, :, 3] > 0)[0]
        return (int(cols.mean()), guard + 2)
    cols = np.where(a[int(h * 0.55), :, 3] > 0)[0]
    return (int(cols.mean()), int(h * 0.55))


