"""Writes CODE_INDEX.md: every script's purpose line and its functions with line numbers.
Run after big changes:  python3 tools/index.py
"""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ["# Code index (generated by tools/index.py, don't edit by hand)", "",
       "Each script: what it is, then `line: function` so you can jump straight to the right lines.", ""]
for f in sorted(os.listdir(ROOT)):
    if not f.endswith(".gd"):
        continue
    lines = open(os.path.join(ROOT, f), encoding="utf-8").read().split("\n")
    doc = ""
    for l in lines[:8]:
        if l.startswith("##"):
            doc = l.lstrip("# ").strip()
            break
    funcs = []
    for i, l in enumerate(lines, 1):
        m = re.match(r"^(static )?func (\w+)", l)
        if m and not m.group(2).startswith("_draw_") :
            funcs.append("%d:%s" % (i, m.group(2)))
    out.append("## %s (%d lines)" % (f, len(lines)))
    if doc:
        out.append(doc)
    out.append(" ".join(funcs))
    out.append("")
open(os.path.join(ROOT, "CODE_INDEX.md"), "w", encoding="utf-8").write("\n".join(out))
print("CODE_INDEX.md:", sum(1 for x in out if x.startswith("## ")), "scripts")
