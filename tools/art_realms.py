"""The realm monsters (floors 251-500) and their bosses. Same letter rules
as art_enemies.py: lowercase = material, UPPERCASE = that material in
shadow, flat w k r y g b, o = dark line. Monsters face left, toward the
hero. Rows can be written short: they're padded with '.' on the right and
empty rows are added at the bottom."""
from art_enemies import add


def A(key, pal, rows, size=None):
    size = size or (48 if key.startswith("boss_") else 32)
    rows = [r.ljust(size, ".") for r in rows]
    for r in rows:
        assert len(r) == size, (key, len(r), r)
    while len(rows) < size:
        rows.append("." * size)
    assert len(rows) == size, (key, len(rows))
    add(key, pal, rows)


